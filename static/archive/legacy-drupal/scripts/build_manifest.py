#!/usr/bin/env python3
"""Walk newwebsite/ and write a manifest.md with every file + its size.

Usage:  python3 scripts/build_manifest.py
"""

from __future__ import annotations

import datetime as _dt
from pathlib import Path

NEWSITE = Path(__file__).resolve().parent.parent
MANIFEST = NEWSITE / "manifest.md"

# Provenance map: where each top-level subtree came from on the source workspace.
PROVENANCE = {
    "content/pages":        "extracted from data/raw/dump-2018-04-12.sql (`node` joined with `field_data_body`, `node_revision`, `url_alias`, `field_data_field_*`)",
    "content/blocks":       "extracted from `block_custom` table (sidebar/footer HTML)",
    "content/blocks_index.json": "index of every entry under content/blocks/",
    "content/menus.json":   "extracted from `menu_links` table",
    "content/users.json":   "extracted from `users` + `users_roles` + `role` (passwords stripped, spam accounts filtered)",
    "content/site_variables.json": "curated subset of `variable` (site_name, theme, etc.)",

    "data/pages_index.csv": "generated by scripts/extract.py",
    "data/url_aliases.json": "extracted from `url_alias` table (Drupal path aliases per node)",
    "data/node_types.json": "extracted from `node_type` table",
    "data/files_managed.json": "extracted from `file_managed` table",
    "data/file_usage.json": "extracted from `file_usage` table",
    "data/page_field_image.json": "extracted from `field_data_field_image`",
    "data/page_field_page_file.json": "extracted from `field_data_field_page_file`",
    "data/page_field_tags.json": "extracted from `field_data_field_tags`",
    "data/taxonomy.json":   "extracted from `taxonomy_vocabulary` + `taxonomy_term_data` + `taxonomy_term_hierarchy` + `taxonomy_index`",
    "data/comments.json":   "extracted from `comment` + `field_data_comment_body`",
    "data/roles.json":      "extracted from `role` + `role_permission`",
    "data/contact_categories.json": "extracted from `contact` table",
    "data/text_formats.json": "extracted from `filter_format` + `filter`",
    "data/drupal_variables.json": "all `variable` rows, PHP-decoded",

    "data/raw/dump-2018-04-12.sql": "verbatim copy of ../dump-2018-04-12.sql",
    "data/raw/drupal_dump.sql": "verbatim copy of ../drupal_dump.sql",

    "media/logos":          "copied from drupal-7.33/sites/default/files/sbpl_logo2_*",
    "media/images":         "copied from drupal-7.33/shared/Images/ (with _thumbs/ from drupal-7.33/shared/_thumbs/Images/)",
    "media/pictures":       "copied from drupal-7.33/sites/default/files/pictures/",
    "media/uploads":        "copied from drupal-7.33/sites/default/files/{Images,ImagesImages,site,_thumbs,resize}/ + drupal-7.33/shared/SBPL/",
    "media/uploads/SBPL":   "drupal-7.33/shared/SBPL/{sbpl.tar.gz,sbpl.zip} + a small index.html",
    "media/videos":         "copied from Desktop/, Downloads/ and drupal-7.33/shared/Venkat/ICRA13/",

    "reference/website_installation_procedure.md": "verbatim copy of ../website_installation_procedure.md",
    "reference/original_settings.php":             "copy of ../settings.php with passwords + drupal_hash_salt redacted",
    "scripts":              "in-tree extraction tooling",
    "README.md":            "human-readable overview of this folder",
    "requirements.txt":     "Python deps (stdlib-only)",
}


def fmt_size(n: int) -> str:
    for unit in ("B", "KB", "MB", "GB"):
        if n < 1024 or unit == "GB":
            return f"{n:>8.1f} {unit}" if unit != "B" else f"{n:>8d} B "
        n /= 1024
    return f"{n} B"


def looks_in(rel: str, prefix: str) -> bool:
    return rel == prefix or rel.startswith(prefix + "/")


def provenance_for(rel: str) -> str:
    # Exact match wins
    if rel in PROVENANCE:
        return PROVENANCE[rel]
    # Directory-prefix match
    for prefix, note in PROVENANCE.items():
        if "/" not in prefix and looks_in(rel, prefix):
            return note
        if looks_in(rel, prefix):
            return note
    return ""


def walk_files():
    for p in sorted(NEWSITE.rglob("*")):
        if p.is_dir():
            continue
        if p == MANIFEST:
            continue
        rel = p.relative_to(NEWSITE).as_posix()
        if rel.startswith("scripts/__pycache__"):
            continue
        yield rel, p.stat().st_size


def main():
    files = list(walk_files())
    total = sum(sz for _, sz in files)

    # Bucket by top-level dir for grouping in the manifest. Files at the
    # repo root go into a synthetic "(top-level)" bucket.
    TOP_LEVEL = "(top-level)"
    by_dir: dict[str, list[tuple[str, int]]] = {}
    for rel, sz in files:
        if "/" in rel:
            top = rel.split("/", 1)[0]
        else:
            top = TOP_LEVEL
        by_dir.setdefault(top, []).append((rel, sz))

    def label(top: str) -> str:
        return top if top == TOP_LEVEL else f"{top}/"

    lines: list[str] = []
    lines.append("# newwebsite/ manifest")
    lines.append("")
    lines.append(f"_Generated: {_dt.datetime.now().isoformat(timespec='seconds')}_")
    lines.append("")
    lines.append(f"**Total: {len(files)} files, {total / (1024 * 1024):.1f} MB**")
    lines.append("")
    lines.append("Sizes for each top-level subtree:")
    lines.append("")
    lines.append("| Subtree | Files | Size |")
    lines.append("|---------|------:|-----:|")
    for top, entries in sorted(by_dir.items()):
        sub_total = sum(sz for _, sz in entries)
        size_str = (
            f"{sub_total / (1024 * 1024):.2f} MB" if sub_total >= 1024 * 1024
            else f"{sub_total / 1024:.1f} KB" if sub_total >= 1024
            else f"{sub_total} B"
        )
        lines.append(f"| `{label(top)}` | {len(entries)} | {size_str} |")
    lines.append("")

    for top in sorted(by_dir):
        lines.append(f"## `{label(top)}`")
        lines.append("")
        if top in PROVENANCE:
            lines.append(f"_Source: {PROVENANCE[top]}_")
            lines.append("")
        lines.append("| Path | Size | Source |")
        lines.append("|------|-----:|--------|")
        for rel, sz in sorted(by_dir[top]):
            note = provenance_for(rel)
            lines.append(f"| `{rel}` | {fmt_size(sz)} | {note} |")
        lines.append("")

    MANIFEST.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Wrote {MANIFEST.relative_to(NEWSITE)} ({len(files)} files, {total/(1024*1024):.1f} MB)")


if __name__ == "__main__":
    main()
